/** t(key, params) — translates with {placeholder} substitution. */
export function makeT(lang) {
  return (key, params) => {
    let s = (I18N[lang] ?? I18N.de)[key] ?? I18N.en[key] ?? key;
    if (params) {
      for (const [k, v] of Object.entries(params)) s = s.split(`{${k}}`).join(v);
    }
    return s;
  };
}

/** React hook: current t(), language, and a setter persisted in the store. */
export function useT() {
  const { state, set } = useStore();
  const lang = LANGS.includes(state.lang) ? state.lang : "de";
  const t = makeT(lang);
  const setLang = (l) => {
    set((s) => ({ ...s, lang: l }));
    document.documentElement.lang = l;
  };
  return { t, lang, setLang };
}
